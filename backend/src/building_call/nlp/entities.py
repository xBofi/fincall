    not_names: tuple[str, ...] = ()
    building_markers: tuple[str, ...] = ()
    #: The script has upper case: names and street names are Title Case tokens. Without case
    #: (Arabic, Devanagari, Urdu) any word token counts, up to three
    cased: bool = True


